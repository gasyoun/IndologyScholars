def public_keyword_label(keyword):
    value = normalize_keyword(keyword)
    return PUBLIC_KEYWORD_LABELS.get(value, keyword)


def keyword_filter_decision(keyword):
    value = normalize_keyword(keyword)
    if not value:
        return value, False, "пустое значение"
    if len(value) < 3:
        return value, False, "короткое служебное слово"
    if re.fullmatch(r"[\d\W_]+", value):
        return value, False, "не лексическое значение"
    if value in KEYWORD_STOPLIST:
        return value, False, KEYWORD_STOPLIST[value]
    return value, True, "предметный термин"


def is_public_keyword(keyword):
    _value, keep, _reason = keyword_filter_decision(keyword)
    return keep


def clean_public_keywords(keywords):
    values = []
    seen = set()
    for keyword in keywords or []:
        value, keep, _reason = keyword_filter_decision(keyword)
        if keep and value not in seen:
            seen.add(value)
            values.append(value)
    return values
